"""Project saved parameter trajectories onto a 2D landscape and draw them.

The landscape file must contain ``coordinates``, ``losses``, ``center``,
``direction_x`` and ``direction_y`` arrays, as generated by the landscape
scripts in this directory.
"""

from __future__ import annotations

import argparse
import csv
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
from numpy.typing import NDArray

FloatArray = NDArray[np.float64]
Projection = tuple[str, FloatArray, FloatArray]


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Overlay projected parameter trajectories on raw loss landscape.")
    parser.add_argument("--landscape", type=Path, required=True, help="landscape.npz containing center and two directions")
    parser.add_argument("--trajectory-file", type=Path, required=True, help=".npz file containing parameter history")
    parser.add_argument("--trajectory-key", default="parameter_history", help="single trajectory key; ignored when --trajectory-keys is set")
    parser.add_argument("--trajectory-keys", default=None, help="comma-separated trajectory keys, e.g. mixed_parameter_history,parameter_history")
    parser.add_argument("--output", type=Path, default=None, help="default: <landscape-dir>/landscape_with_trajectory.png")
    parser.add_argument("--projection-output", type=Path, default=None, help="default: <landscape-dir>/trajectory_projection.npz")
    parser.add_argument("--csv-output", type=Path, default=None, help="default: <landscape-dir>/trajectory_projection.csv")
    parser.add_argument("--title", default="Parameter trajectories projected onto raw loss landscape")
    parser.add_argument("--cmap", default="viridis")
    parser.add_argument("--dpi", type=int, default=150)
    parser.add_argument("--contours", type=int, default=12, help="set 0 to disable contour lines")
    parser.add_argument("--point-size", type=float, default=14.0)
    parser.add_argument("--line-width", type=float, default=1.5)
    parser.add_argument("--arrow-stride", type=int, default=10, help="draw one arrow every N trajectory segments; 0 disables arrows")
    parser.add_argument("--no-wrap", action="store_true", default=False, help="do not wrap angular deltas into [-pi, pi]")
    return parser.parse_args()


def _safe_key(value: str) -> str:
    return "".join(ch if ch.isalnum() or ch in "-_" else "_" for ch in value)


def _trajectory_keys(args: argparse.Namespace) -> list[str]:
    if args.trajectory_keys is None:
        return [str(args.trajectory_key)]
    keys = [item.strip() for item in str(args.trajectory_keys).split(",") if item.strip()]
    if not keys:
        raise ValueError("--trajectory-keys must contain at least one key")
    return keys


def _load_landscape(path: Path) -> tuple[FloatArray, FloatArray, FloatArray, FloatArray, FloatArray, FloatArray]:
    if not path.exists():
        raise FileNotFoundError(f"landscape file not found: {path}")
    data = np.load(path)
    required = ["losses", "center", "direction_x", "direction_y"]
    missing = [key for key in required if key not in data]
    if missing:
        raise KeyError(f"{path} missing required arrays: {missing}; available keys: {list(data.keys())}")
    if "alpha_coordinates" in data and "beta_coordinates" in data:
        alpha_coordinates = np.asarray(data["alpha_coordinates"], dtype=float)
        beta_coordinates = np.asarray(data["beta_coordinates"], dtype=float)
    elif "coordinates" in data:
        alpha_coordinates = np.asarray(data["coordinates"], dtype=float)
        beta_coordinates = alpha_coordinates
    else:
        raise KeyError(f"{path} must contain coordinates or alpha/beta coordinates; got {list(data.keys())}")
    losses = np.asarray(data["losses"], dtype=float)
    center = np.asarray(data["center"], dtype=float).reshape(-1)
    direction_x = np.asarray(data["direction_x"], dtype=float).reshape(-1)
    direction_y = np.asarray(data["direction_y"], dtype=float).reshape(-1)
    if alpha_coordinates.ndim != 1 or beta_coordinates.ndim != 1:
        raise ValueError(f"coordinates must be 1D, got {alpha_coordinates.shape}, {beta_coordinates.shape}")
    if losses.shape != (beta_coordinates.size, alpha_coordinates.size):
        raise ValueError(f"losses must have shape ({beta_coordinates.size}, {alpha_coordinates.size}), got {losses.shape}")
    if center.shape != direction_x.shape or center.shape != direction_y.shape:
        raise ValueError(f"center/directions shape mismatch: {center.shape}, {direction_x.shape}, {direction_y.shape}")
    for name, arr in [("alpha_coordinates", alpha_coordinates), ("beta_coordinates", beta_coordinates), ("losses", losses), ("center", center), ("direction_x", direction_x), ("direction_y", direction_y)]:
        if not np.all(np.isfinite(arr)):
            raise ValueError(f"{name} contains non-finite values")
    return alpha_coordinates, beta_coordinates, losses, center, direction_x, direction_y


def _load_history(path: Path, key: str, expected_size: int) -> FloatArray:
    if not path.exists():
        raise FileNotFoundError(f"trajectory file not found: {path}")
    data = np.load(path)
    if key not in data:
        raise KeyError(f"trajectory key {key!r} not found in {path}; available keys: {list(data.keys())}")
    history = np.asarray(data[key], dtype=float)
    if history.ndim != 2 or history.shape[1] != expected_size:
        raise ValueError(f"trajectory {key!r} must have shape (steps, {expected_size}), got {history.shape}")
    if not np.all(np.isfinite(history)):
        raise ValueError(f"trajectory {key!r} contains non-finite values")
    return history.astype(float, copy=True)


def _project_history(
    history: FloatArray,
    center: FloatArray,
    direction_x: FloatArray,
    direction_y: FloatArray,
    *,
    wrap_angles: bool,
) -> tuple[FloatArray, FloatArray]:
    deltas = history - center.reshape(1, -1)
    if wrap_angles:
        deltas = (deltas + np.pi) % (2.0 * np.pi) - np.pi
    alpha = deltas @ direction_x
    beta = deltas @ direction_y
    return alpha.astype(float), beta.astype(float)


def _write_projection_csv(path: Path, projections: list[Projection]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.writer(handle)
        writer.writerow(["trajectory_key", "iteration", "alpha", "beta"])
        for key, alpha, beta in projections:
            for idx, (a_val, b_val) in enumerate(zip(alpha, beta)):
                writer.writerow([key, idx, float(a_val), float(b_val)])


def _plot_overlay(
    output: Path,
    alpha_coordinates: FloatArray,
    beta_coordinates: FloatArray,
    losses: FloatArray,
    projections: list[Projection],
    *,
    title: str,
    cmap: str,
    dpi: int,
    contours: int,
    point_size: float,
    line_width: float,
    arrow_stride: int,
) -> None:
    output.parent.mkdir(parents=True, exist_ok=True)
    fig, ax = plt.subplots(figsize=(8, 6), constrained_layout=True)
    im = ax.imshow(
        losses,
        origin="lower",
        extent=(alpha_coordinates[0], alpha_coordinates[-1], beta_coordinates[0], beta_coordinates[-1]),
        aspect="auto",
        cmap=cmap,
    )
    if contours > 0:
        levels = np.linspace(float(losses.min()), float(losses.max()), contours)
        ax.contour(alpha_coordinates, beta_coordinates, losses, levels=levels, colors="white", linewidths=0.45, alpha=0.5)

    colors = ["tab:orange", "tab:red", "tab:blue", "tab:green", "tab:purple", "tab:brown"]
    all_scatters = []
    for traj_idx, (key, alpha, beta) in enumerate(projections):
        color = colors[traj_idx % len(colors)]
        steps = np.arange(alpha.size)
        ax.plot(alpha, beta, color=color, linewidth=line_width, alpha=0.9, label=key)
        scatter = ax.scatter(alpha, beta, c=steps, s=point_size, cmap="plasma", edgecolors="black", linewidths=0.2, zorder=3)
        all_scatters.append(scatter)
        ax.scatter([alpha[0]], [beta[0]], marker="o", c=color, s=70, edgecolors="black", linewidths=0.7, zorder=4)
        ax.scatter([alpha[-1]], [beta[-1]], marker="*", c=color, s=120, edgecolors="black", linewidths=0.7, zorder=4)
        if arrow_stride > 0 and alpha.size > 1:
            for idx in range(0, alpha.size - 1, arrow_stride):
                dx = float(alpha[idx + 1] - alpha[idx])
                dy = float(beta[idx + 1] - beta[idx])
                if dx == 0.0 and dy == 0.0:
                    continue
                ax.arrow(
                    float(alpha[idx]),
                    float(beta[idx]),
                    dx,
                    dy,
                    color=color,
                    width=0.0,
                    head_width=0.025 * float(alpha_coordinates[-1] - alpha_coordinates[0]),
                    length_includes_head=True,
                    alpha=0.75,
                    zorder=5,
                )

    ax.scatter([0.0], [0.0], marker="x", c="black", s=70, linewidths=1.4, label="landscape center", zorder=4)
    ax.set_xlabel("alpha along landscape direction 1")
    ax.set_ylabel("beta along landscape direction 2")
    ax.set_title(title)
    ax.legend(loc="upper right")
    loss_cbar = fig.colorbar(im, ax=ax, pad=0.02)
    loss_cbar.set_label("loss")
    if all_scatters:
        step_cbar = fig.colorbar(all_scatters[-1], ax=ax, pad=0.12)
        step_cbar.set_label("iteration")
    fig.savefig(output, dpi=dpi, bbox_inches="tight")
    plt.close(fig)


def main() -> None:
    args = parse_args()
    alpha_coordinates, beta_coordinates, losses, center, direction_x, direction_y = _load_landscape(args.landscape)
    projections: list[Projection] = []
    for key in _trajectory_keys(args):
        history = _load_history(args.trajectory_file, key, center.size)
        alpha, beta = _project_history(
            history,
            center,
            direction_x,
            direction_y,
            wrap_angles=not bool(args.no_wrap),
        )
        projections.append((key, alpha, beta))

    output = args.output or args.landscape.with_name("landscape_with_trajectory.png")
    projection_output = args.projection_output or args.landscape.with_name("trajectory_projection.npz")
    csv_output = args.csv_output or args.landscape.with_name("trajectory_projection.csv")

    arrays: dict[str, NDArray[np.float64] | NDArray[np.int_] | NDArray[np.str_]] = {}
    for key, alpha, beta in projections:
        safe = _safe_key(key)
        arrays[f"{safe}_alpha"] = alpha
        arrays[f"{safe}_beta"] = beta
        arrays[f"{safe}_iterations"] = np.arange(alpha.size, dtype=int)
    arrays["trajectory_keys"] = np.asarray([key for key, _alpha, _beta in projections], dtype=str)
    np.savez(projection_output, **arrays)
    _write_projection_csv(csv_output, projections)
    _plot_overlay(
        output,
        alpha_coordinates,
        beta_coordinates,
        losses,
        projections,
        title=str(args.title),
        cmap=str(args.cmap),
        dpi=int(args.dpi),
        contours=int(args.contours),
        point_size=float(args.point_size),
        line_width=float(args.line_width),
        arrow_stride=int(args.arrow_stride),
    )

    print(f"Saved trajectory overlay: {output}")
    print(f"Saved projection npz: {projection_output}")
    print(f"Saved projection csv: {csv_output}")
    for key, alpha, beta in projections:
        print(f"{key}: steps={alpha.size}, alpha_range=[{float(alpha.min()):.12g}, {float(alpha.max()):.12g}], beta_range=[{float(beta.min()):.12g}, {float(beta.max()):.12g}]")


if __name__ == "__main__":
    main()
